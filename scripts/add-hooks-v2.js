let changed = 0;
const files = fs.readdirSync(dir).filter(f => f.endsWith('.ts') && f !== 'index.ts');

for (const file of files) {
  const slug = file.replace('.ts', '');
  if (!hooksData[slug]) continue;
  const fp = path.join(dir, file);
  let txt = fs.readFileSync(fp, 'utf8');
  const orig = txt;

  for (const [koWord, hookText] of Object.entries(hooksData[slug])) {
    // 이미 hook이 있으면 스킵
    const afterKo = txt.indexOf(`ko: '${koWord}'`);
    if (afterKo === -1) continue;
    // 해당 아이템 블록 끝 찾기 (다음 }, 즉 항목 닫힘)
    const tipIdx = txt.indexOf("tip: '", afterKo);
    if (tipIdx === -1) continue;
    const tipEnd = txt.indexOf("'", tipIdx + 6);
    if (tipEnd === -1) continue;
    // hook 이미 있는지 확인
    const blockEnd = txt.indexOf('},', tipEnd);
    if (blockEnd !== -1 && txt.slice(tipEnd, blockEnd).includes('hook:')) continue;
    // tip 닫힘 따옴표 뒤에 hook 삽입
    const escaped = hookText.replace(/'/g, "\\'");
    txt = txt.slice(0, tipEnd + 1) + `,\n          hook: '${escaped}'` + txt.slice(tipEnd + 1);
  }

  if (txt !== orig) {
    fs.writeFileSync(fp, txt, 'utf8');
    console.log('✅ ' + file);
    changed++;
  }
}
console.log(`\nDone: ${changed} files with hooks added`);
