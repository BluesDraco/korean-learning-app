def fix_mixed_text(text):
    if not text:
        return text
    result = text
    for ko, zh in REPLACEMENTS.items():
        result = result.replace(ko, zh)
    return result

def fix_entry_line(line):
    if not line.strip().startswith('{"id":'):
        return line

    # Fix chinese fields
    line = re.sub(
        r'"(chinese)":\s*"([^"]*)"',
        lambda m: f'"{m.group(1)}":"{fix_mixed_text(m.group(2))}"',
        line
    )
    # Fix scene fields
    line = re.sub(
        r'"(scene)":\s*"([^"]*)"',
        lambda m: f'"{m.group(1)}":"{fix_mixed_text(m.group(2))}"',
        line
    )
    # Fix tags fields
    line = re.sub(
        r'"(tags)":\s*\[([^\]]*)\]',
        lambda m: f'"{m.group(1)}":[{fix_mixed_text(m.group(2))}]',
        line
    )
    return line

def process_file(filepath):
    print(f"Processing: {filepath}")
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    lines = content.split('\n')
    fixed = [fix_entry_line(l) for l in lines]

    with open(filepath, 'w', encoding='utf-8') as f:
        f.write('\n'.join(fixed))

    # Count remaining Hangul in chinese/scene/tags fields
    hangul = re.compile('[가-힯]')
    remaining = 0
    for i, line in enumerate(fixed, 1):
        if 'korean' in line or 'romanization' in line or 'baseForm' in line:
            continue
        if hangul.search(line):
            if re.search(r'"(chinese|scene|tags)":.*[가-힯]', line):
                remaining += 1
                if remaining <= 10:
                    print(f"  REMAINING Line {i}: {line.strip()[:150]}")
    print(f"  Remaining Hangul in Chinese fields: {remaining}")
    print()

