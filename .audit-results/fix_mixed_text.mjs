// Also include single-syllable Hangul replacements in mixed text
const HANGUL_SYLLABLE_IN_CJK = /[가-힣]/;

function fixMixedText(text) {
    if (!text) return text;
    let result = text;
    for (const [ko, zh] of Object.entries(REPLACEMENTS)) {
        result = result.split(ko).join(zh);
    }
    return result;
}

function fixEntryLine(line) {
    if (!line.trim().startsWith('{"id":')) return line;

    // Fix "chinese" fields
    line = line.replace(/"chinese":\s*"([^"]*)"/g, (match, val) => {
        return '"chinese":"' + fixMixedText(val) + '"';
    });
    // Fix "scene" fields
    line = line.replace(/"scene":\s*"([^"]*)"/g, (match, val) => {
        return '"scene":"' + fixMixedText(val) + '"';
    });
    // Fix "tags" fields
    line = line.replace(/"tags":\s*\[([^\]]*)\]/g, (match, val) => {
        return '"tags":[' + fixMixedText(val) + ']';
    });
    return line;
}

function processFile(filepath) {
    console.log(`Processing: ${filepath}`);
    const content = readFileSync(filepath, 'utf-8');
    const lines = content.split('\n');
    const fixed = lines.map(fixEntryLine);

    writeFileSync(filepath, fixed.join('\n'), 'utf-8');

    // Count remaining Hangul in chinese/scene/tags fields
    let remaining = 0;
    for (let i = 0; i < fixed.length; i++) {
        const line = fixed[i];
        if (line.includes('"korean"') || line.includes('"romanization"') || line.includes('"baseForm"')) continue;

        // Check for Hangul in Chinese fields
        const fields = line.match(/"chinese":\s*"([^"]*)"|"(scene)":\s*"([^"]*)"|"(tags)":\s*\[([^\]]*)\]/g);
        if (fields) {
            for (const field of fields) {
                if (HANGUL_SYLLABLE_IN_CJK.test(field)) {
                    remaining++;
                    if (remaining <= 10) {
                        console.log(`  REMAINING Line ${i+1}: ${line.trim().substring(0, 150)}`);
                    }
                }
            }
        }
    }
    console.log(`  Remaining Hangul in Chinese fields: ${remaining}`);
    console.log();
}

const files = process.argv.slice(2);
if (files.length === 0) {
    console.log('Usage: node fix_mixed_text.mjs <file1> <file2> ...');
    process.exit(1);
}
for (const f of files) {
    processFile(f);
}
